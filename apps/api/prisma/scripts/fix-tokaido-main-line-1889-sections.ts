async function main() {
  const envPath = path.resolve(process.cwd(), 'env.development')
  dotenv.config({ path: envPath })

  const prisma = new PrismaService({ useAdapter: true })
  try {
    console.log('\n📜 1889 도카이도 본선 EventSection 갱신 시작 (산문체 + TMI 자연 통합)...')

    const event = await prisma.event.findFirst({
      where: { title: TITLE, deletedAt: null },
      select: { id: true },
    })
    if (!event) {
      console.warn(`  ⚠️  사건 미존재 (제목: ${TITLE}) — 갱신 중단`)
      return
    }

    const eventId = event.id
    console.log(`  ✅ 대상 사건 발견 (id=${eventId})`)

    const deleted = await prisma.eventSection.deleteMany({ where: { eventId } })
    console.log(`  🗑️  기존 섹션 삭제: ${deleted.count}건`)

    console.log('\n  📜 신규 산문체 섹션 등록...')
    for (const section of NEW_SECTIONS) {
      await prisma.eventSection.create({
        data: {
          eventId,
          title: section.title,
          content: section.content,
          order: section.order,
          sectionType: section.sectionType,
        },
      })
      console.log(`    ✅ ${section.title}`)
    }

    console.log(`\n✅ 1889 도카이도 본선 EventSection 갱신 완료 (총 ${NEW_SECTIONS.length}개)\n`)
  } finally {
    await prisma.$disconnect()
  }
}

main()
