async function main() {
  const envPath = path.resolve(process.cwd(), 'env.development')
  dotenv.config({ path: envPath })

  const prisma = new PrismaService({ useAdapter: true })
  let updated = 0
  let notFound = 0

  try {
    console.log('\n📝 인물 전기 일괄 업데이트 시작...\n')

    for (const [originalName, biography] of Object.entries(NEW_BIOS)) {
      const person = await prisma.person.findFirst({
        where: { originalName },
        select: { id: true, name: true, surname: true },
      })
      if (!person) {
        console.warn(`  ⚠️  인물 미존재 (skip): ${originalName}`)
        notFound++
        continue
      }
      await prisma.person.update({
        where: { id: person.id },
        data: { biography },
      })
      const display = [person.surname, person.name].filter(Boolean).join(' ')
      console.log(`  ✅ ${display} (${originalName}) — ${biography.length}자`)
      updated++
    }

    console.log(`\n총 ${updated}명 업데이트 완료${notFound > 0 ? ` (미존재 ${notFound}명)` : ''}\n`)
  } finally {
    await prisma.$disconnect()
  }
}

main()
  .then(() => {
    console.log('✨ 전기 업데이트 완료\n')
  })
  .catch((error) => {
    console.error('\n❌ 업데이트 실패:', error)
    process.exit(1)
  })
