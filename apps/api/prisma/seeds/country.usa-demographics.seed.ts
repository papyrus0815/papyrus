/** PYRAMID_ROWS의 열 순서(연도 다음부터) — 남·여 쌍으로 나열한 18개 필드명. */
const PYRAMID_FIELDS = [
  'maleAge0To9', 'femaleAge0To9',
  'maleAge10To19', 'femaleAge10To19',
  'maleAge20To29', 'femaleAge20To29',
  'maleAge30To39', 'femaleAge30To39',
  'maleAge40To49', 'femaleAge40To49',
  'maleAge50To59', 'femaleAge50To59',
  'maleAge60To69', 'femaleAge60To69',
  'maleAge70To79', 'femaleAge70To79',
  'maleAge80Plus', 'femaleAge80Plus',
] as const

/** VITAL_ROWS의 열 순서(연도 다음부터). */
const VITAL_FIELDS = [
  'population',
  'sexRatio',
  'populationGrowthRate',
  'populationDensity',
  'birthRate',
  'deathRate',
  'fertilityRate',
  'populationAge0To14',
  'populationAge15To64',
  'populationAge65Plus',
  'urbanPopulation',
  'urbanizationRate',
  'lifeExpectancy',
  'lifeExpectancyMale',
  'lifeExpectancyFemale',
  'netMigration',
] as const

/** BigInt 컬럼 — 나머지는 Decimal/Int라 숫자 그대로 넣는다. */
const BIGINT_FIELDS = new Set<string>(['population', 'urbanPopulation'])

export async function seedUsaDemographics(prisma: PrismaService) {
  const country = await prisma.country.findFirst({
    where: { isoCode: 'US' },
    select: { id: true, name: true },
  })
  if (!country) {
    console.warn('⚠️  isoCode=US 국가가 없어 미국 인구 지표 시딩을 건너뜁니다.')
    return
  }

  const vitalsByYear = new Map<number, (number | null)[]>()
  for (const row of VITAL_ROWS) vitalsByYear.set(row[0] as number, row)

  let created = 0
  let updated = 0

  for (const pyramidRow of PYRAMID_ROWS) {
    const year = pyramidRow[0]
    const data: Record<string, unknown> = {}

    PYRAMID_FIELDS.forEach((field, index) => {
      data[field] = BigInt(pyramidRow[index + 1])
    })

    const vitalRow = vitalsByYear.get(year)
    if (vitalRow) {
      VITAL_FIELDS.forEach((field, index) => {
        const value = vitalRow[index + 1]
        if (value == null) {
          data[field] = null
          return
        }
        data[field] = BIGINT_FIELDS.has(field) ? BigInt(value) : value
      })
    }

    const key = { countryId: country.id, year }
    const existing = await prisma.countryDemographicIndicator.findUnique({
      where: { uniq_demographic_indicator_country_year: key },
      select: { id: true },
    })

    await prisma.countryDemographicIndicator.upsert({
      where: { uniq_demographic_indicator_country_year: key },
      create: { ...key, ...data },
      update: data,
    })

    if (existing) updated += 1
    else created += 1
  }

  const first = PYRAMID_ROWS[0][0]
  const last = PYRAMID_ROWS[PYRAMID_ROWS.length - 1][0]
  console.log(
    `✅ ${country.name} 인구 지표 ${PYRAMID_ROWS.length}개 연도 시딩 완료 ` +
      `(신규 ${created} / 갱신 ${updated}, ${first}~${last})`,
  )
}
