export async function seedActOfAbjuration1581(
  prisma: PrismaService,
): Promise<void> {
  console.log('\n📜 1581 단념 선언 시딩 시작 (기존 데이터 보존 모드)...')

  // ── 사전 의존성 조회 ───────────────────────────────────────────────────
  const admin = await prisma.account.findUnique({ where: { username: 'admin' } })
  if (!admin) {
    console.warn('  ⚠️  admin 계정이 없어 시딩을 건너뜀 (먼저 admin.seed 실행 필요)')
    return
  }

  const category = await prisma.eventCategory.findFirst({
    where: { name: EVENT_CATEGORY_NAME },
    select: { id: true },
  })
  if (!category) {
    console.warn(`  ⚠️  사건 카테고리 '${EVENT_CATEGORY_NAME}' 미존재 — 시딩 중단`)
    return
  }

  const habsburgHC = await prisma.historicalCountry.findFirst({
    where: { name: '합스부르크령 네덜란드' },
    select: { id: true },
  })
  const dutchHC = await prisma.historicalCountry.findFirst({
    where: { name: '네덜란드 공화국' },
    select: { id: true },
  })
  if (!habsburgHC || !dutchHC) {
    console.warn('  ⚠️  필수 역사 국가 미존재 — 시딩 중단 (합스부르크령 네덜란드 / 네덜란드 공화국)')
    return
  }

  // ── 1) 사건 등록 (존재 시 스킵) ─────────────────────────────────────────
  const TITLE = '단념 선언'
  const START_DATE = '1581-07-26'

  const existing = await prisma.event.findFirst({
    where: {
      title: TITLE,
      startDate: new Date(START_DATE),
      deletedAt: null,
    },
  })

  let eventId: string
  if (existing) {
    eventId = existing.id
    console.log(`  ⏭️  사건 이미 존재 — 스킵: ${TITLE} (id=${eventId})`)
  } else {
    const created = await prisma.event.create({
      data: {
        title: TITLE,
        ...EVENT_BODY,
        startDate: new Date(START_DATE),
        startDatePrecision: 'day',
        endDate: new Date(START_DATE),
        endDatePrecision: 'day',
        categoryId: category.id,
        historicalCountryId: dutchHC.id,
        createdById: admin.id,
      },
    })
    eventId = created.id
    console.log(`  ✅ 생성: ${TITLE} (id=${eventId})`)
  }

  // ── 2) EventSection (각 섹션 단위로 존재 시 스킵) ────────────────────────
  for (const section of SECTIONS) {
    const exists = await prisma.eventSection.findFirst({
      where: { eventId, title: section.title },
    })
    if (exists) {
      console.log(`    ⏭️  섹션 스킵 (이미 존재): ${section.title}`)
      continue
    }
    await prisma.eventSection.create({
      data: {
        eventId,
        title: section.title,
        content: section.content,
        order: section.order,
        sectionType: section.sectionType ?? null,
      },
    })
    console.log(`    ✅ 섹션 생성: ${section.title}`)
  }

  // ── 3) EventCountryRelation (존재 시 스킵) ─────────────────────────────
  type RelInput = {
    historicalCountryId: string
    historicalCountryName: string
    role: EventCountryRole
    roleDescription: string
  }
  const RELATIONS: RelInput[] = [
    {
      historicalCountryId: dutchHC.id,
      historicalCountryName: '네덜란드 공화국',
      role: EventCountryRole.INITIATOR,
      roleDescription:
        '선언 주체. 1579 위트레흐트 동맹으로 결성된 북부 7개 주(홀란트·제일란트·위트레흐트·' +
        '프리슬란트·흐로닝언·오버레이셀·헬더를란트) 의회(Staten-Generaal)가 ' +
        '1581-07-26 헤이그에서 단념 선언을 통과시켜 합스부르크령 네덜란드에서 분리, ' +
        '네덜란드 공화국(1581~1795 약 214년 존속)으로 출발. ' +
        '약 67년 후인 1648 베스트팔렌 조약으로 국제법상 정식 인정. ' +
        '17세기 황금시대(VOC·환은행·렘브란트·스피노자) → 1689 잉글랜드 권리장전 → ' +
        '1776 미국 독립선언서(토머스 제퍼슨 명시 참조) → 1789 프랑스 인권선언으로 이어지는 ' +
        '근대 입헌주의 계보의 직접 출발점.',
    },
    {
      historicalCountryId: habsburgHC.id,
      historicalCountryName: '합스부르크령 네덜란드',
      role: EventCountryRole.TARGET,
      roleDescription:
        '단념 대상국. 1482년 부르고뉴 마리아의 합스부르크 결혼으로 시작된 ' +
        '합스부르크령 네덜란드(1482~1581)가 1581-07-26 단념 선언으로 북부 7개 주를 상실, ' +
        '약 99년 만에 형식적으로 종결. 펠리페 2세(재위 1556~1598)의 ' +
        '(1)알바 공작 파견 후 피의 평의회·약 1만 명 처형 (2)종교재판소 강화 ' +
        '(3)에그몬트·호른 등 가톨릭 귀족 불법 처형 (4)과도한 세금 부과 등 ' +
        '약 30건의 신민 권리 침해 사례가 단념 선언의 직접 정당화 논거가 되었다. ' +
        '합스부르크령 네덜란드의 잔여 영토(남부 10개 주)는 1581 아라스 동맹(1579)에 따라 ' +
        '스페인령 네덜란드(1581~1714)로 재편, ' +
        '17세기 80년 전쟁 진행 중 1648 베스트팔렌 조약으로 스페인 영지로 정식 확정되었다.',
    },
  ]

  for (const rel of RELATIONS) {
    const exists = await prisma.eventCountryRelation.findFirst({
      where: {
        eventId,
        historicalCountryId: rel.historicalCountryId,
        role: rel.role,
      },
    })
    if (exists) {
      console.log(`    ⏭️  국가관계 스킵 (이미 존재): ${rel.historicalCountryName}`)
      continue
    }
    await prisma.eventCountryRelation.create({
      data: {
        eventId,
        historicalCountryId: rel.historicalCountryId,
        role: rel.role,
        roleDescription: rel.roleDescription,
      },
    })
    console.log(`    ✅ 국가관계: ${rel.historicalCountryName} (${rel.role})`)
  }

  console.log(`✅ 1581 단념 선언 시딩 완료\n`)
}
