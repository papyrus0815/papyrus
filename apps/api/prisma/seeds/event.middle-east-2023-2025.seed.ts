// ── 메인 시드 함수 ────────────────────────────────────────────────────────
export async function seedMiddleEast20232025(
  prisma: PrismaService,
): Promise<void> {
  console.log('\n📜 2023-2025 중동 사건 12건 시딩 시작 (기존 데이터 보존 모드)...')

  // ── 사전 의존성 조회 ───────────────────────────────────────────────────
  const admin = await prisma.account.findUnique({ where: { username: 'admin' } })
  if (!admin) {
    console.warn('  ⚠️  admin 계정 미존재 — 시딩 중단')
    return
  }

  // 카테고리 매핑
  const categories = await prisma.eventCategory.findMany({ select: { id: true, name: true } })
  const categoryIdByName = new Map(categories.map((c) => [c.name, c.id]))

  // 국가 매핑
  const countries = await prisma.country.findMany({ select: { id: true, name: true } })
  const countryIdByName = new Map(countries.map((c) => [c.name, c.id]))

  // ── 1) 신규 인물 등록 ────────────────────────────────────────────────────
  console.log('\n  👥 신규 인물 등록...')
  const personIdByOriginalName = new Map<string, string>()

  // 기존 인물도 매핑에 포함
  const allPersons = await prisma.person.findMany({
    where: {
      originalName: {
        in: [
          'Donald John Trump',
          'Benjamin Netanyahu',
          'Ali Hosseini Khamenei',
          'Masoud Pezeshkian',
          'Hossein Salami',
          'Mohammad Bagheri',
          'Amir Ali Hajizadeh',
          'Herzi Halevi',
        ],
      },
    },
    select: { id: true, originalName: true },
  })
  for (const p of allPersons) {
    if (p.originalName) personIdByOriginalName.set(p.originalName, p.id)
  }

  for (const p of NEW_PERSONS) {
    const existing = await prisma.person.findFirst({
      where: { originalName: p.originalName },
    })
    let personId: string
    if (existing) {
      personId = existing.id
      console.log(`    ⏭️  ${p.originalName} (이미 존재)`)
    } else {
      const created = await prisma.person.create({
        data: {
          name: p.name,
          surname: p.surname,
          originalName: p.originalName,
          biography: p.biography,
          birthEra: 'AD' as any,
          birthDate: new Date(p.birthYear, p.birthMonth - 1, p.birthDay),
          deathEra: p.deathYear ? ('AD' as any) : undefined,
          deathDate: p.deathYear
            ? new Date(p.deathYear, (p.deathMonth ?? 1) - 1, p.deathDay ?? 1)
            : undefined,
          deathCause: p.deathCause,
          isAlive: p.isAlive,
          gender: p.gender,
          nameDisplayOrder: 'western',
          influence: p.influence,
          accountId: ACCOUNT_ID,
        },
      })
      personId = created.id
      console.log(`    ✅ ${p.originalName} (영향력 ${p.influence})`)
    }
    personIdByOriginalName.set(p.originalName, personId)

    // 소속국가
    const cId = countryIdByName.get(p.countryName)
    if (cId) {
      const affExists = await prisma.personCountryAffiliation.findFirst({
        where: { personId, countryId: cId, affiliationType: 'CITIZENSHIP' as any },
      })
      if (!affExists) {
        await prisma.personCountryAffiliation.create({
          data: { personId, countryId: cId, affiliationType: 'CITIZENSHIP' as any, priority: 0 },
        })
      }
    }
  }

  // ── 2) 사건 등록 ────────────────────────────────────────────────────────
  for (const e of EVENTS) {
    console.log(`\n  📍 ${e.title}`)

    const catId = categoryIdByName.get(e.category)
    if (!catId) {
      console.warn(`    ⚠️  카테고리 미존재: ${e.category} — 스킵`)
      continue
    }

    const existing = await prisma.event.findFirst({
      where: {
        title: e.title,
        startDate: new Date(e.startDate),
        deletedAt: null,
      },
    })

    let eventId: string
    if (existing) {
      eventId = existing.id
      console.log(`    ⏭️  사건 이미 존재 — 스킵 (id=${eventId})`)
    } else {
      const created = await prisma.event.create({
        data: {
          title: e.title,
          description: e.description,
          location: e.location,
          background: e.background,
          aftermath: e.aftermath,
          startDate: new Date(e.startDate),
          startDatePrecision: e.startPrecision ?? 'day',
          endDate: e.endDate ? new Date(e.endDate) : null,
          endDatePrecision: e.endPrecision ?? 'day',
          categoryId: catId,
          keywords: e.keywords as any,
          createdById: admin.id,
        },
      })
      eventId = created.id
      console.log(`    ✅ 사건 생성 (id=${eventId})`)
    }

    // 섹션
    for (const s of e.sections) {
      const exists = await prisma.eventSection.findFirst({
        where: { eventId, title: s.title },
      })
      if (exists) {
        console.log(`      ⏭️  섹션 스킵: ${s.title}`)
        continue
      }
      await prisma.eventSection.create({
        data: {
          eventId,
          title: s.title,
          content: s.content,
          order: s.order,
          sectionType: s.sectionType ?? null,
        },
      })
      console.log(`      ✅ 섹션: ${s.title}`)
    }

    // 국가 관계
    for (const rel of e.relations) {
      const cId = countryIdByName.get(rel.countryName)
      if (!cId) {
        console.warn(`      ⚠️  국가 미존재: ${rel.countryName}`)
        continue
      }
      const exists = await prisma.eventCountryRelation.findFirst({
        where: { eventId, countryId: cId, role: rel.role },
      })
      if (exists) {
        console.log(`      ⏭️  국가관계 스킵: ${rel.countryName}`)
        continue
      }
      await prisma.eventCountryRelation.create({
        data: {
          eventId,
          countryId: cId,
          role: rel.role,
          roleDescription: rel.roleDescription,
        },
      })
      console.log(`      ✅ 국가관계: ${rel.countryName} (${rel.role})`)
    }

    // 인물 관계
    for (const pe of e.persons ?? []) {
      const personId = personIdByOriginalName.get(pe.originalName)
      if (!personId) {
        console.warn(`      ⚠️  인물 미존재: ${pe.originalName}`)
        continue
      }
      const exists = await prisma.personEvent.findFirst({
        where: { personId, eventId },
      })
      if (exists) {
        console.log(`      ⏭️  인물관계 스킵: ${pe.originalName}`)
        continue
      }
      await prisma.personEvent.create({
        data: { personId, eventId, role: pe.role, note: pe.note },
      })
      console.log(`      ✅ 인물관계: ${pe.originalName}`)
    }
  }

  console.log(`\n✅ 2023-2025 중동 12건 시딩 완료\n`)
}
