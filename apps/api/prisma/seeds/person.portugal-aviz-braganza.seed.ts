// ────────────────────────────────────────────────────────────────────────────
export async function seedPortugalAvizBraganza(prisma: PrismaService): Promise<void> {
  console.log('\n👑 포르투갈 아비스 후반 + 합스부르크 + 브라간사 초반 라인업 시딩 시작 (기존 데이터 보존 모드)...')

  const admin = await prisma.account.findUnique({ where: { username: 'admin' } })
  if (!admin) {
    console.warn('  ⚠️  admin 계정 미존재')
    return
  }

  const portugalHC = await prisma.historicalCountry.findFirst({
    where: { name: '포르투갈 왕국' },
    select: { id: true },
  })
  if (!portugalHC) {
    console.warn('  ⚠️  포르투갈 왕국 HC 미존재 — 시딩 중단')
    return
  }

  const kingPos = await prisma.governmentPositionDefinition.findFirst({
    where: { title: '국왕' },
    select: { id: true },
  })
  if (!kingPos) {
    console.warn('  ⚠️  관직 정의 \'국왕\' 미존재 — 시딩 중단')
    return
  }
  console.log(`  관직 ID: 국왕 = ${kingPos.id}`)

  // ── 0) 가문 등록 (브라간사 신규, 아비스 lookup) ────────────────────────
  const dynastyIdByName: Record<string, string> = {}
  for (const d of DYNASTIES) {
    const exists = await prisma.dynasty.findFirst({ where: { name: d.name } })
    if (exists) {
      console.log(`  ⏭️  가문 스킵: ${d.name} (id=${exists.id})`)
      dynastyIdByName[d.name] = exists.id
      continue
    }
    const created = await prisma.dynasty.create({
      data: {
        name: d.name,
        description: d.description,
        startDate: new Date(d.startYear, d.startMonth - 1, d.startDay),
        endDate: new Date(d.endYear, d.endMonth - 1, d.endDay),
      },
    })
    console.log(`  ✅ 가문 생성: ${d.name} (id=${created.id})`)
    dynastyIdByName[d.name] = created.id
  }
  // 아비스 가문 lookup (기등록)
  const aviz = await prisma.dynasty.findFirst({ where: { name: '아비스 가문' } })
  if (aviz) {
    dynastyIdByName['아비스 가문'] = aviz.id
    console.log(`  🔍 가문 매핑: 아비스 가문 (id=${aviz.id})`)
  } else {
    console.warn('  ⚠️  아비스 가문 미존재 — 아비스 후반 인물의 dynastyId 비워둠')
  }

  // ── 1) Person 등록 (8명 신규) ──────────────────────────────────────────
  const personIdByOriginalName: Record<string, string> = {}
  for (const spec of ALL_NEW_KINGS) {
    const existing = await prisma.person.findFirst({
      where: { originalName: spec.originalName },
    })
    if (existing) {
      console.log(`  ⏭️  인물 스킵: ${spec.originalName} (id=${existing.id})`)
      personIdByOriginalName[spec.originalName] = existing.id
      continue
    }
    const created = await prisma.person.create({
      data: {
        name: spec.name,
        surname: spec.surname || undefined,
        originalName: spec.originalName,
        regnalName: spec.regnalName || undefined,
        biography: spec.biography,
        birthDate: new Date(spec.birthYear, spec.birthMonth - 1, spec.birthDay),
        birthEra: 'AD' as any,
        deathDate: new Date(spec.deathYear, spec.deathMonth - 1, spec.deathDay),
        deathEra: 'AD' as any,
        gender: spec.gender,
        nameDisplayOrder: 'western' as any,
        dynastyId: spec.dynastyName ? dynastyIdByName[spec.dynastyName] : undefined,
        birthPlaceText: spec.birthPlaceText,
        deathPlaceText: spec.deathPlaceText,
        deathType: spec.deathType,
        deathCause: spec.deathCause,
        deathNote: spec.deathNote,
        influence: spec.influence,
        accountId: admin.id,
      },
    })
    console.log(`  ✅ 인물 생성: ${spec.originalName} (id=${created.id})`)
    personIdByOriginalName[spec.originalName] = created.id
  }

  // ── 2) 기등록 인물 lookup (Manuel I·Philip II·Philip III) ──────────────
  for (const original of ['Manuel I of Portugal', 'Philip II of Spain', 'Philip III of Spain']) {
    const p = await prisma.person.findFirst({
      where: { originalName: original },
      select: { id: true },
    })
    if (p) {
      personIdByOriginalName[original] = p.id
      console.log(`  🔍 인물 매핑: ${original} (id=${p.id})`)
    } else {
      console.warn(`  ⚠️  기등록 인물 미발견: ${original}`)
    }
  }

  // ── 3) PersonStats (신규 8명) ──────────────────────────────────────────
  for (const spec of ALL_NEW_KINGS) {
    const pid = personIdByOriginalName[spec.originalName]
    if (!pid) continue
    const exists = await prisma.personStats.findFirst({
      where: { personId: pid, accountId: admin.id },
    })
    if (exists) {
      console.log(`    ⏭️  ${spec.originalName} 능력치 스킵`)
      continue
    }
    await prisma.personStats.create({
      data: {
        personId: pid,
        accountId: admin.id,
        politics: spec.stats.politics,
        military: spec.stats.military,
        diplomacy: spec.stats.diplomacy,
        intellect: spec.stats.intellect,
        charisma: spec.stats.charisma,
        administration: spec.stats.administration,
        notes: spec.stats.notes,
      },
    })
    console.log(
      `    ✅ ${spec.originalName} 능력치: ` +
        `정${spec.stats.politics}·군${spec.stats.military}·외${spec.stats.diplomacy}·` +
        `학${spec.stats.intellect}·카${spec.stats.charisma}·행${spec.stats.administration}`,
    )
  }

  // ── 4) PersonCountryAffiliation (8명 → 포르투갈 왕국 CITIZENSHIP) ─────
  // (Philip IV는 스페인 출생이지만 포르투갈 23대로 통치했으므로 포르투갈 시민권 등록)
  for (const spec of ALL_NEW_KINGS) {
    const pid = personIdByOriginalName[spec.originalName]
    if (!pid) continue
    const exists = await prisma.personCountryAffiliation.findFirst({
      where: {
        personId: pid,
        historicalCountryId: portugalHC.id,
        affiliationType: 'CITIZENSHIP' as any,
      },
    })
    if (exists) continue
    await prisma.personCountryAffiliation.create({
      data: {
        personId: pid,
        historicalCountryId: portugalHC.id,
        affiliationType: 'CITIZENSHIP' as any,
        priority: 0,
      },
    })
  }
  console.log(`  ✅ 소속국가 처리: ${ALL_NEW_KINGS.length}명 → 포르투갈 왕국`)

  // ── 5) SovereignReign 등록 (포르투갈 18·19·20·23·24·25·26·27대) ───────
  type ReignBundle = {
    personId: string
    label: string
    regnalNumber: number
    regnalName: string
    startDate: Date
    endDate: Date
    appointmentMethod: AppointmentMethod
    endReason: TenureEndReason
    endReasonDetail: string
    notes: string
  }
  const allReigns: ReignBundle[] = []
  for (const spec of ALL_NEW_KINGS) {
    const pid = personIdByOriginalName[spec.originalName]
    if (!pid) continue
    allReigns.push({
      personId: pid,
      label: spec.regnalName ? `${spec.name} ${spec.regnalName}` : spec.name,
      regnalNumber: spec.reign.regnalNumber,
      regnalName: spec.reign.regnalName,
      startDate: new Date(spec.reign.startYear, spec.reign.startMonth - 1, spec.reign.startDay),
      endDate: new Date(spec.reign.endYear, spec.reign.endMonth - 1, spec.reign.endDay),
      appointmentMethod: spec.reign.appointmentMethod,
      endReason: spec.reign.endReason,
      endReasonDetail: spec.reign.endReasonDetail,
      notes: spec.reign.notes,
    })
  }

  for (const r of allReigns) {
    // 같은 (person, HC=포르투갈) 기등록 확인
    const existing = await prisma.sovereignReign.findFirst({
      where: { personId: r.personId, historicalCountryId: portugalHC.id },
    })
    if (existing) {
      const needs =
        existing.regnalNumber !== r.regnalNumber ||
        existing.regnalName !== r.regnalName ||
        existing.startDate.getTime() !== r.startDate.getTime() ||
        (existing.endDate?.getTime() ?? null) !== r.endDate.getTime()
      if (needs) {
        await prisma.sovereignReign.update({
          where: { id: existing.id },
          data: {
            regnalNumber: r.regnalNumber,
            regnalName: r.regnalName,
            startDate: r.startDate,
            endDate: r.endDate,
            appointmentMethod: r.appointmentMethod,
            endReason: r.endReason,
            endReasonDetail: r.endReasonDetail,
            notes: r.notes,
            positionDefinitionId: kingPos.id,
          },
        })
        console.log(`  🔧 재임 정정: 포르투갈 ${r.regnalName} ${r.regnalNumber}대 (${r.label})`)
      } else {
        console.log(`  ⏭️  재임 스킵 (정확): 포르투갈 ${r.regnalName} ${r.regnalNumber}대`)
      }
      continue
    }
    // 슬롯 충돌
    const slotConflict = await prisma.sovereignReign.findFirst({
      where: { historicalCountryId: portugalHC.id, regnalNumber: r.regnalNumber },
    })
    if (slotConflict) {
      console.warn(
        `  ⚠️  재임 충돌: 포르투갈 ${r.regnalNumber}대 — 다른 인물 점유 (skip ${r.label})`,
      )
      continue
    }
    await prisma.sovereignReign.create({
      data: {
        personId: r.personId,
        historicalCountryId: portugalHC.id,
        positionDefinitionId: kingPos.id,
        regnalNumber: r.regnalNumber,
        regnalName: r.regnalName,
        startDate: r.startDate,
        endDate: r.endDate,
        appointmentMethod: r.appointmentMethod,
        endReason: r.endReason,
        endReasonDetail: r.endReasonDetail,
        notes: r.notes,
        accountId: admin.id,
      },
    })
    console.log(
      `  ✅ 재임: 포르투갈 ${r.regnalName} ${r.regnalNumber}대 (${r.startDate.getUTCFullYear()}~${r.endDate.getUTCFullYear()})`,
    )
  }

  // ── 6) 부자 관계 ──────────────────────────────────────────────────────
  // 아비스: Manuel I → 주앙 3세, Manuel I → 엔리케 1세
  // 브라간사: 주앙 4세 → 아폰수 6세, 주앙 4세 → 페드루 2세, 페드루 2세 → 주앙 5세
  // 펠리페 4세: 펠리페 3세(=Philip III of Spain) → 펠리페 4세
  // (세바스티앙 1세는 손자라서 부친 없음 — 부친 후안 마누엘 미등록)
  const manuelId = personIdByOriginalName['Manuel I of Portugal']
  const joaoIIIid = personIdByOriginalName['John III of Portugal']
  const henryIid = personIdByOriginalName['Henry, King of Portugal']
  const philipIIIid = personIdByOriginalName['Philip III of Spain']
  const philipIVid = personIdByOriginalName['Philip IV of Spain']
  const joaoIVid = personIdByOriginalName['John IV of Portugal']
  const afonsoVIid = personIdByOriginalName['Afonso VI of Portugal']
  const pedroIIid = personIdByOriginalName['Pedro II of Portugal']
  const joaoVid = personIdByOriginalName['John V of Portugal']

  const fatherLinks: [string | undefined, string | undefined, string][] = [
    [manuelId, joaoIIIid, '마누엘 1세 → 주앙 3세'],
    [manuelId, henryIid, '마누엘 1세 → 엔리케 1세'],
    [philipIIIid, philipIVid, '펠리페 3세(스페인) → 펠리페 4세(스페인) / 포르투갈 펠리페 3세'],
    [joaoIVid, afonsoVIid, '주앙 4세 → 아폰수 6세'],
    [joaoIVid, pedroIIid, '주앙 4세 → 페드루 2세'],
    [pedroIIid, joaoVid, '페드루 2세 → 주앙 5세'],
  ]
  for (const [fid, cid, label] of fatherLinks) {
    if (!fid || !cid) {
      console.warn(`  ⚠️  부자 스킵 (id 누락): ${label}`)
      continue
    }
    const child = await prisma.person.findUnique({ where: { id: cid }, select: { fatherId: true } })
    if (child?.fatherId) {
      console.log(`  ⏭️  부자 스킵 (이미 연결): ${label}`)
      continue
    }
    await prisma.person.update({ where: { id: cid }, data: { fatherId: fid } })
    console.log(`  ✅ 부자: ${label}`)
  }

  console.log(`✅ 포르투갈 아비스 후반 + 브라간사 초반 라인업 시딩 완료\n`)
}
