export async function seedWorldWarOneAppointmentDetails(prisma: PrismaService): Promise<void> {
  console.log('\n📜 WWI 인물 재임 취임 배경(appointmentDetail) 보강 시작...')

  // 인물 슬러그 → id
  const personIdBySlug = new Map<string, string>()
  for (const [slug, key] of Object.entries(PERSON_KEYS)) {
    const found = await prisma.person.findFirst({
      where: { originalName: { contains: key } },
      select: { id: true },
    })
    if (found) personIdBySlug.set(slug, found.id)
    else console.warn(`  ⚠️  인물 미등록 — 건너뜀: ${slug} (등록 후 재실행하면 백필된다)`)
  }

  let filled = 0
  let kept = 0
  let missing = 0
  for (const entry of ENTRIES) {
    const personId = personIdBySlug.get(entry.person)
    if (!personId) {
      missing++
      continue
    }
    const startDate = new Date(entry.start[0], entry.start[1] - 1, entry.start[2])
    const tenure = await prisma.governmentPositionTenure.findFirst({
      where: { personId, startDate },
      select: { id: true, title: true, appointmentDetail: true },
    })
    if (!tenure) {
      console.warn(`  ⚠️  재임 없음 — 건너뜀: ${entry.person} / ${entry.title} (${entry.start.join('-')})`)
      missing++
      continue
    }
    // 사용자가 이미 써 넣은 경위는 보존한다
    if (tenure.appointmentDetail && tenure.appointmentDetail.trim().length > 0) {
      kept++
      continue
    }
    await prisma.governmentPositionTenure.update({
      where: { id: tenure.id },
      data: { appointmentDetail: entry.detail },
    })
    filled++
    console.log(`  ✅ ${entry.person}: ${tenure.title ?? entry.title} (${entry.detail.length}자)`)
  }

  console.log(`📜 취임 배경 보강 완료 — 신규 ${filled}건 · 기존 보존 ${kept}건 · 대상 없음 ${missing}건\n`)
}
