/**
 * 국가명 약칭 — 좁은 메타 열에서 **이름이 읽히게** 한다.
 *
 * 왜 필요한가: 역사국가는 국기 이모지가 없어 칩이 곧 국가명인데, 정식 명칭은
 * '그레이트브리튼 및 아일랜드 연합왕국'(19자 = 153px)처럼 어떤 메타 열 예산으로도
 * 담을 수 없는 길이다. 실측(1600px 뷰포트, 목록 293행)에서 관련국 칩 521개 중
 * **190개(36%)가 말줄임**됐고, 그중 다수는 '독일 …' · '러시아 …'처럼 **잘린 뒤
 * 남는 글자가 국가를 특정하지 못하는** 상태였다(독일 제국/독일 연방 공화국).
 *
 * 규약
 *  1. 통용 약칭이 있는 이름만 **명시 표**로 바꾼다(추론 금지). '독일 제국 → 독일'처럼
 *     정체 접미사를 기계적으로 떼면 시대가 다른 국가가 한 이름으로 합쳐진다.
 *  2. 소비에트 연방 구성국은 규칙이 성립한다('우크라이나 소비에트 사회주의 공화국'
 *     → '우크라이나 SSR'). 접미사가 **국가를 특정하는 부분이 아니라** 소속 표기라서다.
 *  3. 나머지 이름의 괄호 주석은 뗀다 — 괄호 안은 편집용 구분자('(근대)', '(독일 점령기)')
 *     이지 이름이 아니다. 단 1번 표가 먼저 이긴다('독일 민주 공화국 (동독)' → '동독';
 *     괄호만 떼면 오히려 긴 정식명이 남는다).
 *
 * ⚠️ 약칭은 **표시에만** 쓴다. 툴팁·스크린리더 라벨·검색은 정식 명칭을 그대로 써야 한다
 *    (약칭은 되돌릴 수 없는 손실이고, 같은 약칭을 쓰는 다른 국가가 있을 수 있다).
 */

/** 통용 약칭 표 — '더 짧은 이름'이 아니라 **한국어에서 그 국가를 부르는 이름**만 넣는다. */
const CANONICAL_SHORT_NAMES: Record<string, string> = {
  '그레이트브리튼 및 아일랜드 연합왕국': '영국',
  '그레이트브리튼 및 북아일랜드 연합왕국': '영국',
  '그레이트브리튼 왕국': '영국',
  '소비에트 사회주의 공화국 연방': '소련',
  '러시아 소비에트 연방 사회주의 공화국': '소비에트 러시아',
  '유고슬라비아 사회주의 연방 공화국': '유고슬라비아',
  '유고슬라비아 연방 공화국': '유고슬라비아',
  '독일 연방 공화국 (서독)': '서독',
  '독일 민주 공화국 (동독)': '동독',
  조선민주주의인민공화국: '북한',
  '오스트리아-헝가리 제국': '오스트리아-헝가리',
}

/** 소련 구성 공화국 — '<지명> 소비에트 사회주의 공화국'은 통째로 'SSR'로 접는다. */
const SOVIET_REPUBLIC = /^(.+?)\s*소비에트\s*사회주의\s*공화국$/

/** 이름 뒤 괄호 주석 — '(근대)' · '(이탈리아 보호령)'처럼 편집용 구분자. */
const TRAILING_PARENTHETICAL = /\s*[(（][^()（）]*[)）]\s*$/

export const shortenCountryName = (name: string): string => {
  const trimmed = name.trim()
  if (!trimmed) return name

  const canonical = CANONICAL_SHORT_NAMES[trimmed]
  if (canonical) return canonical

  const soviet = trimmed.match(SOVIET_REPUBLIC)
  if (soviet) return `${soviet[1].trim()} SSR`

  const withoutNote = trimmed.replace(TRAILING_PARENTHETICAL, '')
  /* 괄호가 이름의 전부인 병리적 입력에서 빈 문자열을 돌려주지 않는다. */
  return withoutNote || trimmed
}
